#!/usr/bin/env python3
"""Draws the app icon (64x64, 1 bit: a printer with a page coming out) and writes apps/trmnl-print/icon.h (1 = white)
and shots/icon.png. Needs Pillow."""
from PIL import Image, ImageDraw

S = 8
im = Image.new("L", (64 * S, 64 * S), 255)
d = ImageDraw.Draw(im)

def R(x0, y0, x1, y1, **kw):
    d.rectangle((x0 * S, y0 * S, x1 * S - 1, y1 * S - 1), **kw)

R(16, 6, 48, 24, fill=255, outline=0, width=3 * S)      # the page going in at the top
for y in (12, 17):
    d.line((22 * S, y * S, 42 * S, y * S), fill=0, width=2 * S)
R(5, 22, 59, 44, fill=0)                                # the body
R(48, 28, 54, 31, fill=255)                             # a light
R(14, 40, 50, 60, fill=255, outline=0, width=3 * S)     # the page coming out
for y in (47, 52):
    d.line((20 * S, y * S, 44 * S, y * S), fill=0, width=2 * S)
im = im.resize((64, 64), Image.BOX).point(lambda v: 0 if v < 128 else 255, "1")
im.save("shots/icon.png")
px = im.load()
out = []
for y in range(64):
    for x in range(0, 64, 8):
        out.append(sum((1 if px[x + k, y] else 0) << (7 - k) for k in range(8)))
with open("apps/trmnl-print/icon.h", "w") as f:
    f.write("/* Generated by tools/icon.py: the 64x64 app icon for APP_ICON (1 = white). */\n#define PRINT_ICON \\\n")
    for i in range(0, 512, 16):
        f.write("    " + ", ".join("0x%02X" % v for v in out[i:i + 16]) + (", \\\n" if i + 16 < 512 else "\n"))
